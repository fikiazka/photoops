-- PhotoOps Nicio Studio — struktur basis data PostgreSQL 16/17 (14 tabel).
-- Jalankan pada database kosong: psql -d photoops_si3_dev -v ON_ERROR_STOP=1 -f database/001_schema.sql
--
-- Database menjaga kunci (PK/FK), keunikan, nilai wajib, dan pilihan nilai (CHECK).
-- Aturan yang melibatkan banyak baris divalidasi PHP di dalam transaksi dengan SELECT ... FOR UPDATE:
--   - unit Studio tidak boleh dipakai dua proyek pada jadwal yang beririsan;
--   - satu alokasi hanya boleh keluar satu kali;
--   - jumlah kembali tidak boleh melebihi jumlah keluar.

SET client_encoding = 'UTF8';

BEGIN;

-- Nomor urut kode dokumen. Aplikasi mengambil nextval() lalu membentuk kode, mis. PRJ-026.
CREATE SEQUENCE seq_kode_proyek;
CREATE SEQUENCE seq_kode_transaksi;
CREATE SEQUENCE seq_kode_insiden;

-- 1. Akun login. Peran login: sa = Super Admin, pi = Petugas Inventaris, us = User/Kru.
CREATE TABLE pengguna (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama           VARCHAR(60)  NOT NULL,
    username       VARCHAR(30)  NOT NULL CONSTRAINT uq_pengguna_username UNIQUE,
    email          VARCHAR(80)  NOT NULL CONSTRAINT uq_pengguna_email UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    peran          VARCHAR(2)   NOT NULL CHECK (peran IN ('sa', 'pi', 'us')),
    jenis_anggota  VARCHAR(10)  NOT NULL DEFAULT 'Internal' CHECK (jenis_anggota IN ('Internal', 'Freelancer')),
    telepon        VARCHAR(20)  NOT NULL DEFAULT '',
    status         VARCHAR(8)   NOT NULL DEFAULT 'Aktif' CHECK (status IN ('Aktif', 'Nonaktif'))
);

-- 2. Kategori perlengkapan. nomor_terakhir = nomor kode unit terakhir (CAM-005 -> 5).
CREATE TABLE kategori_perlengkapan (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama            VARCHAR(50)  NOT NULL UNIQUE,
    kode_awalan     VARCHAR(5)   NOT NULL UNIQUE,
    deskripsi       VARCHAR(150) NOT NULL DEFAULT '',
    nomor_terakhir  INTEGER      NOT NULL DEFAULT 0 CHECK (nomor_terakhir >= 0)
);

-- 3. Inventaris Studio: satu baris = satu unit fisik. Barang Rental dan Milik Kru tidak masuk tabel ini.
CREATE TABLE perlengkapan (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_unit     VARCHAR(12)  NOT NULL UNIQUE,
    nama          VARCHAR(60)  NOT NULL,
    merek         VARCHAR(30)  NOT NULL,
    kategori_id   INTEGER      NOT NULL REFERENCES kategori_perlengkapan (id),
    kondisi       VARCHAR(11)  NOT NULL DEFAULT 'Baik' CHECK (kondisi IN ('Baik', 'Maintenance', 'Rusak')),
    status_aktif  VARCHAR(8)   NOT NULL DEFAULT 'Aktif' CHECK (status_aktif IN ('Aktif', 'Nonaktif')),
    catatan       VARCHAR(120) NOT NULL DEFAULT ''
);

-- 4. Proyek/acara. Setiap proyek punya satu PIC (pengguna). selesai = jadwal acara, bukan batas pengembalian barang.
CREATE TABLE proyek (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode                VARCHAR(12)  NOT NULL UNIQUE,
    nama                VARCHAR(80)  NOT NULL,
    klien               VARCHAR(80)  NOT NULL,
    lokasi              VARCHAR(80)  NOT NULL,
    mulai               TIMESTAMP    NOT NULL,
    selesai             TIMESTAMP    NOT NULL,
    deadline_persiapan  TIMESTAMP    NOT NULL,
    status              VARCHAR(11)  NOT NULL DEFAULT 'Draf'
                        CHECK (status IN ('Draf', 'Dijadwalkan', 'Berlangsung', 'Selesai', 'Dibatalkan')),
    pic_id              INTEGER      NOT NULL REFERENCES pengguna (id),
    catatan             VARCHAR(300) NOT NULL DEFAULT '',
    dibuat_oleh         INTEGER      NOT NULL REFERENCES pengguna (id),
    CONSTRAINT ck_proyek_jadwal   CHECK (selesai >= mulai),
    CONSTRAINT ck_proyek_deadline CHECK (deadline_persiapan <= mulai)
);

-- 5. Kru proyek: relasi banyak-ke-banyak antara proyek dan pengguna. PIC tidak dicatat di sini.
CREATE TABLE anggota_proyek (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyek_id    INTEGER NOT NULL REFERENCES proyek (id) ON DELETE CASCADE,
    pengguna_id  INTEGER NOT NULL REFERENCES pengguna (id),
    UNIQUE (proyek_id, pengguna_id)
);

-- 6. Preset: template daftar kebutuhan untuk jenis acara tertentu.
CREATE TABLE preset_perlengkapan (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama         VARCHAR(50)  NOT NULL UNIQUE,
    deskripsi    VARCHAR(160) NOT NULL DEFAULT '',
    dibuat_oleh  INTEGER      NOT NULL REFERENCES pengguna (id),
    diubah_pada  TIMESTAMP    NOT NULL
);

-- 7. Isi preset. nama_perlengkapan adalah nama model (teks), bukan unit tertentu.
CREATE TABLE detail_preset (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    preset_id          INTEGER     NOT NULL REFERENCES preset_perlengkapan (id) ON DELETE CASCADE,
    nama_perlengkapan  VARCHAR(60) NOT NULL,
    kategori_id        INTEGER     NOT NULL REFERENCES kategori_perlengkapan (id),
    jumlah             INTEGER     NOT NULL CHECK (jumlah BETWEEN 1 AND 20),
    UNIQUE (preset_id, nama_perlengkapan)
);

-- 8. Kebutuhan barang suatu proyek, per kategori.
CREATE TABLE kebutuhan_proyek (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyek_id    INTEGER     NOT NULL REFERENCES proyek (id) ON DELETE CASCADE,
    nama         VARCHAR(60) NOT NULL,
    acuan        VARCHAR(60) NOT NULL DEFAULT '',
    kategori_id  INTEGER     NOT NULL REFERENCES kategori_perlengkapan (id),
    jumlah       INTEGER     NOT NULL CHECK (jumlah BETWEEN 1 AND 50)
);

-- 9. Barang yang dialokasikan untuk memenuhi kebutuhan. Proyeknya diketahui lewat kebutuhan_id.
--    Sumber: Studio (unit perlengkapan), Rental (dari vendor), Milik Kru (barang pribadi anggota).
--    Kolom diterima_*, sewa_mulai, jatuh_tempo_vendor, kontak_vendor, dan dikembalikan_vendor_* khusus Rental.
CREATE TABLE alokasi_barang (
    id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kebutuhan_id              INTEGER      NOT NULL REFERENCES kebutuhan_proyek (id) ON DELETE CASCADE,
    sumber                    VARCHAR(9)   NOT NULL CHECK (sumber IN ('Studio', 'Rental', 'Milik Kru')),
    perlengkapan_id           INTEGER      REFERENCES perlengkapan (id),
    nama_barang               VARCHAR(60)  NOT NULL DEFAULT '',
    vendor                    VARCHAR(60)  NOT NULL DEFAULT '',
    pemilik_id                INTEGER      REFERENCES pengguna (id),
    jumlah                    INTEGER      NOT NULL DEFAULT 1 CHECK (jumlah >= 1),
    tgl_mulai                 DATE         NOT NULL,
    tgl_selesai               DATE         NOT NULL,
    status                    VARCHAR(12)  NOT NULL DEFAULT 'Dikonfirmasi'
                              CHECK (status IN ('Direncanakan', 'Dikonfirmasi', 'Dibatalkan')),
    catatan                   VARCHAR(120) NOT NULL DEFAULT '',
    diperiksa                 BOOLEAN      NOT NULL DEFAULT FALSE,
    diterima_pada             TIMESTAMP,
    diterima_oleh             INTEGER      REFERENCES pengguna (id),
    kondisi_terima            VARCHAR(11)  CHECK (kondisi_terima IN ('Baik', 'Maintenance', 'Rusak')),
    catatan_terima            VARCHAR(120) NOT NULL DEFAULT '',
    sewa_mulai                DATE,
    jatuh_tempo_vendor        DATE,
    kontak_vendor             VARCHAR(60)  NOT NULL DEFAULT '',
    dikembalikan_vendor_pada  TIMESTAMP,
    dikembalikan_vendor_oleh  INTEGER      REFERENCES pengguna (id),
    kondisi_kembali_vendor    VARCHAR(11)  CHECK (kondisi_kembali_vendor IN ('Baik', 'Maintenance', 'Rusak')),
    catatan_kembali_vendor    VARCHAR(120) NOT NULL DEFAULT '',
    CONSTRAINT ck_alokasi_tanggal CHECK (tgl_selesai >= tgl_mulai),
    -- Kolom wajib sesuai sumber barang.
    CONSTRAINT ck_alokasi_sumber CHECK (
           (sumber = 'Studio'    AND perlengkapan_id IS NOT NULL AND jumlah = 1)
        OR (sumber = 'Rental'    AND perlengkapan_id IS NULL AND nama_barang <> '' AND vendor <> '')
        OR (sumber = 'Milik Kru' AND perlengkapan_id IS NULL AND nama_barang <> '' AND pemilik_id IS NOT NULL)
    ),
    -- Hanya alokasi yang dikonfirmasi yang boleh dicentang di checklist persiapan.
    CONSTRAINT ck_alokasi_diperiksa CHECK (diperiksa = FALSE OR status = 'Dikonfirmasi'),
    -- Barang sewaan baru bisa dikembalikan ke vendor setelah diterima.
    CONSTRAINT ck_alokasi_kembali_vendor CHECK (dikembalikan_vendor_pada IS NULL OR (diterima_pada IS NOT NULL AND dikembalikan_vendor_pada >= diterima_pada)),
    CONSTRAINT ck_alokasi_masa_sewa CHECK (jatuh_tempo_vendor IS NULL OR sewa_mulai IS NULL OR jatuh_tempo_vendor >= sewa_mulai)
);

-- 10. Persiapan H-1 (satu baris per proyek). Ketepatan waktu = dikonfirmasi_pada dibanding proyek.deadline_persiapan.
--     batal_* menyimpan pembatalan konfirmasi terakhir; riwayat lengkapnya ada di riwayat_aktivitas.
CREATE TABLE persiapan_proyek (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyek_id              INTEGER   NOT NULL UNIQUE REFERENCES proyek (id) ON DELETE CASCADE,
    diperbarui_pada        TIMESTAMP,
    diperbarui_oleh        INTEGER   REFERENCES pengguna (id),
    dikonfirmasi_pada      TIMESTAMP,
    dikonfirmasi_oleh      INTEGER   REFERENCES pengguna (id),
    batal_pada             TIMESTAMP,
    batal_oleh             INTEGER   REFERENCES pengguna (id),
    batal_otomatis         BOOLEAN,
    batal_alasan           TEXT      NOT NULL DEFAULT '',
    batal_konfirmasi_pada  TIMESTAMP,
    batal_konfirmasi_oleh  INTEGER   REFERENCES pengguna (id)
);

-- 11. Kepala transaksi serah terima: barang Keluar ke proyek atau Kembali dari proyek.
--     penerima/penyerah menyimpan nama saat kejadian (histori), *_id menunjuk akunnya.
CREATE TABLE transaksi_barang (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode          VARCHAR(12)  NOT NULL UNIQUE,
    proyek_id     INTEGER      NOT NULL REFERENCES proyek (id),
    jenis         VARCHAR(7)   NOT NULL CHECK (jenis IN ('Keluar', 'Kembali')),
    waktu         TIMESTAMP    NOT NULL,
    petugas_id    INTEGER      NOT NULL REFERENCES pengguna (id),
    penerima      VARCHAR(60)  NOT NULL DEFAULT '',
    penerima_id   INTEGER      REFERENCES pengguna (id),
    penyerah      VARCHAR(60)  NOT NULL DEFAULT '',
    penyerah_id   INTEGER      REFERENCES pengguna (id),
    catatan       VARCHAR(300) NOT NULL DEFAULT '',
    dicatat_pada  TIMESTAMP
);

-- 12. Rincian barang per transaksi. Pengembalian boleh bertahap dan dipecah per kondisi.
--     Sisa barang di luar dihitung lewat view v_saldo_alokasi, tidak disimpan.
CREATE TABLE detail_transaksi (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaksi_id  INTEGER     NOT NULL REFERENCES transaksi_barang (id),
    alokasi_id    INTEGER     NOT NULL REFERENCES alokasi_barang (id),
    kondisi       VARCHAR(11) NOT NULL DEFAULT 'Baik' CHECK (kondisi IN ('Baik', 'Maintenance', 'Rusak')),
    jumlah        INTEGER     NOT NULL DEFAULT 1 CHECK (jumlah >= 1),
    UNIQUE (transaksi_id, alokasi_id, kondisi)
);

-- 13. Laporan insiden, hanya untuk unit Studio (perlengkapan_id wajib).
--     detail_id terisi bila insiden tercatat otomatis saat pengembalian.
CREATE TABLE laporan_insiden (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode             VARCHAR(12) NOT NULL UNIQUE,
    perlengkapan_id  INTEGER     NOT NULL REFERENCES perlengkapan (id),
    proyek_id        INTEGER     REFERENCES proyek (id) ON DELETE SET NULL,
    detail_id        INTEGER     UNIQUE REFERENCES detail_transaksi (id),
    jenis            VARCHAR(14) NOT NULL CHECK (jenis IN ('Rusak', 'Masalah Teknis')),
    waktu            TIMESTAMP   NOT NULL,
    deskripsi        TEXT        NOT NULL,
    status           VARCHAR(10) NOT NULL DEFAULT 'Dilaporkan' CHECK (status IN ('Dilaporkan', 'Ditangani', 'Selesai')),
    pelapor_id       INTEGER     NOT NULL REFERENCES pengguna (id)
);

-- 14. Log aktivitas (hanya ditambah). pengguna_id kosong = dicatat sistem.
--     objek berupa teks agar log tetap utuh walau data aslinya dihapus.
CREATE TABLE riwayat_aktivitas (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waktu        TIMESTAMP    NOT NULL,
    pengguna_id  INTEGER      REFERENCES pengguna (id),
    aksi         VARCHAR(20)  NOT NULL CHECK (aksi IN (
                     'Barang Keluar', 'Pengembalian', 'Insiden', 'Alokasi', 'Rental', 'Persiapan',
                     'Proyek', 'Kebutuhan', 'Tim', 'Preset', 'Perlengkapan', 'Pengguna')),
    objek        VARCHAR(200) NOT NULL DEFAULT '',
    keterangan   TEXT         NOT NULL DEFAULT '',
    lama         VARCHAR(200) NOT NULL DEFAULT '',
    baru         VARCHAR(200) NOT NULL DEFAULT ''
);

-- Indeks untuk kolom yang sering dipakai JOIN/filter. PostgreSQL tidak membuat indeks FK secara otomatis.
CREATE INDEX idx_kebutuhan_proyek     ON kebutuhan_proyek (proyek_id);
CREATE INDEX idx_alokasi_kebutuhan    ON alokasi_barang (kebutuhan_id);
CREATE INDEX idx_alokasi_perlengkapan ON alokasi_barang (perlengkapan_id);
CREATE INDEX idx_detail_alokasi       ON detail_transaksi (alokasi_id);
CREATE INDEX idx_transaksi_proyek     ON transaksi_barang (proyek_id);
CREATE INDEX idx_riwayat_waktu        ON riwayat_aktivitas (waktu);

-- Saldo per alokasi yang pernah keluar: jumlah keluar - jumlah kembali.
-- Ditulis dengan CTE: langkah 1 barang keluar, langkah 2 total kembali, langkah 3 digabung.
CREATE VIEW v_saldo_alokasi AS
WITH keluar AS (
    SELECT d.alokasi_id,
           d.transaksi_id,
           d.jumlah,
           t.waktu
    FROM detail_transaksi d
    JOIN transaksi_barang t ON t.id = d.transaksi_id
    WHERE t.jenis = 'Keluar'
),
kembali AS (
    SELECT d.alokasi_id,
           SUM(d.jumlah)                                                    AS jumlah,
           SUM(CASE WHEN d.kondisi = 'Baik'        THEN d.jumlah ELSE 0 END) AS baik,
           SUM(CASE WHEN d.kondisi = 'Maintenance' THEN d.jumlah ELSE 0 END) AS maintenance,
           SUM(CASE WHEN d.kondisi = 'Rusak'       THEN d.jumlah ELSE 0 END) AS rusak,
           MAX(t.waktu)                                                     AS terakhir
    FROM detail_transaksi d
    JOIN transaksi_barang t ON t.id = d.transaksi_id
    WHERE t.jenis = 'Kembali'
    GROUP BY d.alokasi_id
)
SELECT a.id                                AS alokasi_id,
       k.proyek_id,
       a.sumber,
       keluar.transaksi_id                 AS trx_keluar,
       keluar.waktu                        AS waktu_keluar,
       keluar.jumlah                       AS jumlah_keluar,
       COALESCE(kembali.jumlah, 0)         AS jumlah_kembali,
       keluar.jumlah - COALESCE(kembali.jumlah, 0) AS sisa,
       COALESCE(kembali.baik, 0)           AS kembali_baik,
       COALESCE(kembali.maintenance, 0)    AS kembali_maintenance,
       COALESCE(kembali.rusak, 0)          AS kembali_rusak,
       kembali.terakhir                    AS kembali_terakhir,
       CASE
           WHEN COALESCE(kembali.jumlah, 0) = 0 THEN 'Belum Kembali'
           WHEN kembali.jumlah < keluar.jumlah  THEN 'Kembali Sebagian'
           ELSE 'Sudah Kembali'
       END                                 AS status_kembali
FROM alokasi_barang a
JOIN kebutuhan_proyek k ON k.id = a.kebutuhan_id
JOIN keluar             ON keluar.alokasi_id = a.id
LEFT JOIN kembali       ON kembali.alokasi_id = a.id;

COMMIT;
